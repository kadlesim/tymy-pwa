export function tr(cs: string, vars?: Vars): string {
  const source = lang() === 'en' ? (EN[cs] ?? cs) : cs
  if (!vars) return source
  return source.replace(/\{(\w+)\}/g, (_match, name: string) => String(vars[name] ?? ''))
}
